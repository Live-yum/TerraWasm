'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { makeCircuitWorld } = require('./helpers/circuit-world');
for (const target of ['node', 'web']) test(`${target}: world checkpoint cannot allocate or mutate a foreign pixel owner`, async () => {
  const build = path.resolve(process.env.TCW_BUILD_DIR || path.join(__dirname, '../build'));
  const name = target === 'web' ? 'terrax_world_wasm_web' : 'terrax_world_wasm';
  const M = await require(path.join(build, `${name}.js`))({ wasmBinary: fs.readFileSync(path.join(build, `${name}.wasm`)) });
  const pointers = [], alloc = n => { const p = M._tx_malloc(n); assert.ok(p); pointers.push(p); return p; };
  const hp = alloc(4), stats = alloc(96), cells = alloc(12), bytes = makeCircuitWorld([], 8, 8), input = alloc(bytes.length);
  M.HEAPU8.set(bytes, input);
  const task = M._terra_world_open_begin(input, bytes.length); assert.ok(task);
  let status = 10;
  for (let i = 0; i < 1000 && status === 10; i++) status = M._terra_world_open_step(task, 64);
  assert.equal(status, 0); assert.equal(M._terra_world_open_finish(task, hp), 0);
  const world = M.HEAPU32[hp / 4]; assert.equal(M._terra_world_task_close(task), 0);
  assert.equal(M._terra_pixel_workspace_create(64, 64, 8 * 1024 * 1024, 1024 * 1024, 256, hp), 0);
  const pixel = M.HEAPU32[hp / 4];
  assert.equal(M._terra_pixel_workspace_palette_add(pixel, 0xabcdef, hp), 0);
  const color = M.HEAPU32[hp / 4];
  assert.equal(M._terra_pixel_workspace_tx_begin(pixel), 0);
  M.HEAPU32.set([2, 3, color], cells / 4); assert.equal(M._terra_pixel_workspace_cells(pixel, cells, 1), 0);
  assert.equal(M._terra_world_workspace_begin(world, 8 * 1024 * 1024, hp), 0);
  const token = M.HEAPU32[hp / 4], heap = M._tx_native_heap_used();
  assert.equal(M._terra_pixel_workspace_stats(pixel, stats), 0);
  const before = Buffer.from(M.HEAPU8.subarray(stats, stats + 96));
  assert.equal(M._terra_pixel_workspace_create(64, 64, 8 * 1024 * 1024, 1024 * 1024, 256, hp), -3);
  assert.equal(M.HEAPU32[hp / 4], 0);
  assert.equal(M._terra_pixel_workspace_cells(pixel, 0, 1), -3, 'owner rejection precedes invalid mutation rollback');
  assert.equal(M._terra_pixel_workspace_tx_rollback(pixel), -3);
  assert.equal(M._terra_pixel_workspace_tx_commit(pixel), -3);
  assert.equal(M._terra_pixel_workspace_close(pixel), -3);
  assert.equal(M._terra_pixel_workspace_read_rect(pixel, 2, 3, 1, 1, hp, 1), 0);
  assert.equal(M.HEAPU8[hp] + M.HEAPU8[hp + 1] * 256, color);
  assert.equal(M._terra_pixel_workspace_stats(pixel, stats), 0);
  assert.deepEqual(Buffer.from(M.HEAPU8.subarray(stats, stats + 96)), before);
  assert.equal(M._tx_native_heap_used(), heap);
  assert.equal(M._terra_world_workspace_rollback(world, token), 0);
  assert.equal(M._terra_pixel_workspace_tx_commit(pixel), 0);
  assert.equal(M._terra_pixel_workspace_undo(pixel), 0);
  assert.equal(M._terra_pixel_workspace_redo(pixel), 0);
  assert.equal(M._terra_pixel_workspace_close(pixel), 0);
  assert.equal(M._terra_world_close(world), 0);
  for (const p of pointers) M._tx_free(p);
  assert.equal(M._tx_native_heap_used(), 0); assert.equal(M._tx_bridge_heap_used(), 0);
});
