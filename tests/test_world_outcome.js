'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { makeCircuitWorld } = require('./helpers/circuit-world');
for (const target of ['node', 'web']) test(`${target}: fixed outcome wire admission, commit, caller rollback and cached output`, async () => {
  const build = path.resolve(process.env.TCW_BUILD_DIR || path.join(__dirname, '../build'));
  const name = target === 'web' ? 'terrax_world_wasm_web' : 'terrax_world_wasm';
  const M = await require(path.join(build, `${name}.js`))({ wasmBinary: fs.readFileSync(path.join(build, `${name}.wasm`)) });
  assert.equal(M._terra_world_outcome_abi_version(), 2);
  const pointers=[], alloc=n=>{const p=M._tx_malloc(n);assert.ok(p);pointers.push(p);return p;};
  const str=s=>{const b=Buffer.from(s+'\0'),p=alloc(b.length);M.HEAPU8.set(b,p);return p;};
  const hp=alloc(4), out=alloc(40), needed=alloc(8), response=alloc(4096), bytes=makeCircuitWorld([],8,8), input=alloc(bytes.length);
  M.HEAPU8.set(bytes,input);const task=M._terra_world_open_begin(input,bytes.length);assert.ok(task);
  let code=10;for(let i=0;i<1000&&code===10;i++)code=M._terra_world_open_step(task,64);
  assert.equal(code,0);assert.equal(M._terra_world_open_finish(task,hp),0);const h=M.HEAPU32[hp/4];assert.equal(M._terra_world_task_close(task),0);
  const op=str('header_patch'),request=str('{"patch":{"worldName":"receipt commit"}}'),bad=str('{"patch":{"tilesWide":9}}');
  const check=(status,effect,state,before,after)=>{
    const view=new DataView(M.HEAPU8.buffer,out,40);
    assert.deepEqual(Array.from({length:6},(_,i)=>view.getUint32(i*4,true)),[40,2,status,effect,state,0]);
    assert.equal(view.getBigUint64(24,true),BigInt(before));assert.equal(view.getBigUint64(32,true),BigInt(after));
  };
  const exec=(req=request,options=0,buffer=0,capacity=0n)=>M._terra_op_execute_json_receipt(h,op,req,buffer,capacity,needed,options,out,40);
  assert.equal(M._terra_op_execute_json_receipt(h,op,request,0,0n,needed,0,0,40),1);
  assert.equal(M._terra_op_execute_json_receipt(h,1,request,0,0n,needed,0,out,40),1);check(1,0,0,0,0);
  assert.equal(exec(),0);check(0,1,2,0,1);
  assert.equal(exec(request,0,response,4096n),0);check(0,0,0,1,1);
  assert.equal(M._terra_world_workspace_begin(h,8*1024*1024,hp),0);const token=M.HEAPU32[hp/4];
  const joined=str('{"patch":{"worldName":"provisional"}}');
  assert.equal(exec(joined),8);check(8,0,1,1,1);
  assert.equal(exec(joined,1),0);check(0,1,1,1,1);
  const failure=exec(bad,1);assert.notEqual(failure,0);check(failure,2,3,1,1);
  assert.equal(M._terra_world_workspace_rollback_receipt(h,token,out,40),8);check(8,0,0,1,1);
  assert.equal(M._terra_world_workspace_begin(h,8*1024*1024,hp),0);const token2=M.HEAPU32[hp/4];
  assert.equal(M._terra_world_workspace_commit_receipt(h,token2,out,40),0);check(0,1,2,1,2);
  assert.equal(M._terra_world_close(h),0);for(const p of pointers)M._tx_free(p);
  assert.equal(M._tx_native_heap_used(),0);assert.equal(M._tx_bridge_heap_used(),0);
});
