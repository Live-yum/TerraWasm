'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { makeCircuitWorld } = require('./helpers/circuit-world');
for (const target of ['node', 'web']) test(`${target}: player queries remain temporary and graph admission preserves a pending traversal`, async () => {
  const build = path.resolve(process.env.TCW_BUILD_DIR || path.join(__dirname, '../build'));
  const name = target === 'web' ? 'terrax_world_wasm_web' : 'terrax_world_wasm';
  const M = await require(path.join(build, `${name}.js`))({ wasmBinary: fs.readFileSync(path.join(build, `${name}.wasm`)) });
  const pointers = [], alloc = n => { const p = M._tx_malloc(n); assert.ok(p); pointers.push(p); return p; };
  const hp = alloc(4), stats = alloc(64), cells = alloc(32), step = alloc(16), events = alloc(128);
  const wld = makeCircuitWorld([], 8, 8), input = alloc(wld.length); M.HEAPU8.set(wld, input);
  const task = M._terra_world_open_begin(input, wld.length); assert.ok(task);
  let state = 10; for (let n = 0; n < 1000 && state === 10; n++) state = M._terra_world_open_step(task, 64);
  assert.equal(state, 0); assert.equal(M._terra_world_open_finish(task, hp), 0);
  const world = M.HEAPU32[hp / 4]; assert.equal(M._terra_world_task_close(task), 0);
  const json = Buffer.concat([fs.readFileSync(path.join(__dirname, 'fixtures/minimal-player.json')), Buffer.from([0])]);
  const jp = alloc(json.length); M.HEAPU8.set(json, jp);
  assert.equal(M._terra_plr_open_json(jp, hp), 0); const player = M.HEAPU32[hp / 4];
  assert.equal(M._terra_plr_get_json(player, 0, 0n, hp), 0); const jsonSize = M.HEAPU32[hp / 4], outputJson = alloc(jsonSize);
  assert.equal(M._terra_plr_get_json(player, outputJson, BigInt(jsonSize), hp), 0);
  const expectedJson = Buffer.from(M.HEAPU8.subarray(outputJson, outputJson + jsonSize));
  assert.equal(M._terra_plr_save_to_buffer(player, 0, 0, hp), 0); const encodedSize = M.HEAPU32[hp / 4], output = alloc(encodedSize);
  assert.equal(M._terra_plr_save_to_buffer(player, output, encodedSize, hp), 0);
  const expectedBytes = Buffer.from(M.HEAPU8.subarray(output, output + encodedSize));
  assert.equal(M._terra_plr_release_caches(player), 0);
  assert.equal(M._terra_circuit_create(8, 8, 8, 1024 * 1024, hp), 0); const circuit = M.HEAPU32[hp / 4];
  M.HEAPU32.set([2, 3, 1, 0, 3, 3, 1, 1], cells / 4);
  assert.equal(M._terra_circuit_load(circuit, cells, 2), 0); assert.equal(M._terra_circuit_compile(circuit, 8, hp), 0);
  assert.equal(M._terra_circuit_begin(circuit, cells, 1, 0, 0, 64), 0);
  assert.equal(M._terra_world_workspace_begin(world, 8 * 1024 * 1024, hp), 0); const token = M.HEAPU32[hp / 4];
  const heap = M._tx_native_heap_used(); assert.equal(M._terra_circuit_stats(circuit, stats), 0);
  const before = Buffer.from(M.HEAPU8.subarray(stats, stats + 64)); assert.ok(M.HEAPU32[stats / 4 + 10]);
  assert.equal(M._txw_use_builtin_map_runtime(), -1);
  assert.equal(M._txw_set_map_runtime(0, 0), -1);
  assert.equal(M._terra_plr_open_json(jp, hp), 8); assert.equal(M.HEAPU32[hp / 4], 0);
  assert.equal(M._terra_plr_replace_json(player, jp), 8);
  assert.equal(M._terra_plr_release_caches(player), 8); assert.equal(M._terra_plr_close(player), 8);
  for (let n = 0; n < 3; n++) {
    assert.equal(M._terra_plr_get_json(player, 0, 0n, hp), 0); assert.equal(M.HEAPU32[hp / 4], jsonSize);
    assert.equal(M._terra_plr_get_json(player, outputJson, BigInt(jsonSize), hp), 0);
    assert.deepEqual(Buffer.from(M.HEAPU8.subarray(outputJson, outputJson + jsonSize)), expectedJson);
    assert.equal(M._terra_plr_save_to_buffer(player, output, encodedSize, hp), 0);
    assert.deepEqual(Buffer.from(M.HEAPU8.subarray(output, output + encodedSize)), expectedBytes);
    assert.equal(M._tx_native_heap_used(), heap, 'queries publish no cache into the foreign checkpoint');
  }
  assert.equal(M._terra_circuit_create(8, 8, 8, 1024 * 1024, hp), -3); assert.equal(M.HEAPU32[hp / 4], 0);
  assert.equal(M._terra_circuit_step(circuit, 8, events, 8, step), -3);
  assert.equal(M._terra_circuit_cancel(circuit), -3); assert.equal(M._terra_circuit_close(circuit), -3);
  assert.equal(M._terra_circuit_stats(circuit, stats), 0); assert.deepEqual(Buffer.from(M.HEAPU8.subarray(stats, stats + 64)), before);
  assert.equal(M._terra_world_workspace_rollback(world, token), 0);
  assert.equal(M._terra_plr_get_json(player, outputJson, BigInt(jsonSize), hp), 0);
  assert.deepEqual(Buffer.from(M.HEAPU8.subarray(outputJson, outputJson + jsonSize)), expectedJson);
  assert.equal(M._terra_plr_save_to_buffer(player, output, encodedSize, hp), 0);
  assert.deepEqual(Buffer.from(M.HEAPU8.subarray(output, output + encodedSize)), expectedBytes);
  state = 1; for (let n = 0; n < 64 && state === 1; n++) state = M._terra_circuit_step(circuit, 8, events, 8, step);
  assert.equal(state, 0); assert.ok(M.HEAPU32[step / 4 + 3] >= 2);
  assert.equal(M._terra_circuit_close(circuit), 0); assert.equal(M._terra_plr_close(player), 0); assert.equal(M._terra_world_close(world), 0);
  for (const p of pointers) M._tx_free(p);
  assert.equal(M._tx_native_heap_used(), 0); assert.equal(M._tx_bridge_heap_used(), 0);
});
